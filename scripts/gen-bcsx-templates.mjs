// Regenerates lib/bcsx-templates.generated.ts from assets/bcsx-templates/*.xlsx.
// Run with: node scripts/gen-bcsx-templates.mjs
// Use this after editing one of the template workbooks (e.g. to fix a label or a
// cell that should stay blank) so the base64 baked into the app stays in sync.
import fs from "node:fs";
import path from "node:path";

const dir = "assets/bcsx-templates";
const tags = ["s1", "s2", "a0"];
let out = "// AUTO-GENERATED by scripts/gen-bcsx-templates.mjs — do not edit by hand.\n";
out += "// Base64-encoded blank BCSX_NMD single-day templates (S1/S2/A0), derived from the\n";
out += "// original 16.09.2026 report files with only the manual-entry cells cleared.\n";
for (const tag of tags) {
  const buf = fs.readFileSync(path.join(dir, `bcsx-${tag}-template.xlsx`));
  out += `export const BCSX_TEMPLATE_${tag.toUpperCase()}_BASE64 = ${JSON.stringify(buf.toString("base64"))};\n`;
}
fs.writeFileSync("lib/bcsx-templates.generated.ts", out);
console.log("wrote lib/bcsx-templates.generated.ts —", out.length, "chars");
