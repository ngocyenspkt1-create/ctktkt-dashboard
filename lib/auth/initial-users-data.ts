export async function seedUsersAndPositions(rawDb: ReturnType<typeof import("@/db").getRawDb>) {
  // 1. Đảm bảo cấu trúc bảng tồn tại
  try {
    await rawDb.prepare(`
      CREATE TABLE IF NOT EXISTS position_permissions (
        id integer PRIMARY KEY AUTOINCREMENT NOT NULL,
        position text NOT NULL,
        role text DEFAULT 'viewer' NOT NULL,
        permissions text DEFAULT '[]' NOT NULL,
        description text DEFAULT '' NOT NULL,
        updated_at text DEFAULT CURRENT_TIMESTAMP NOT NULL
      )
    `).run();
    await rawDb.prepare(`CREATE UNIQUE INDEX IF NOT EXISTS uidx_position_permissions_position ON position_permissions (position)`).run();
  } catch {}

  // 2. Thêm cột mới vào users nếu chưa có
  const alterColumns = [
    "ALTER TABLE users ADD COLUMN employee_code text",
    "ALTER TABLE users ADD COLUMN position text",
    "ALTER TABLE users ADD COLUMN department text DEFAULT 'Vận hành 1' NOT NULL",
    "ALTER TABLE users ADD COLUMN email_company text",
    "ALTER TABLE users ADD COLUMN email_work text",
    "ALTER TABLE users ADD COLUMN phone text",
    "ALTER TABLE users ADD COLUMN status text DEFAULT 'active' NOT NULL",
  ];
  for (const sql of alterColumns) {
    try {
      await rawDb.prepare(sql).run();
    } catch {}
  }

  // 3. Khởi tạo 25 Cương vị mặc định
  let positionsSeeded = 0;
  for (const pos of DEFAULT_POSITIONS) {
    try {
      const existing = await rawDb.prepare("SELECT id FROM position_permissions WHERE position = ?").bind(pos.position).first();
      if (!existing) {
        await rawDb.prepare(
          "INSERT INTO position_permissions (position, role, permissions, description) VALUES (?, ?, ?, ?)"
        ).bind(pos.position, pos.role, JSON.stringify(pos.permissions), pos.description).run();
        positionsSeeded++;
      }
    } catch {}
  }

  // 4. Khởi tạo 124 Người dùng
  let usersSeeded = 0;
  for (const u of INITIAL_USERS) {
    const cleanUsername = u.username.trim().toLowerCase();
    try {
      const existing = await rawDb.prepare("SELECT id FROM users WHERE LOWER(username) = ?").bind(cleanUsername).first();
      const pHash = hashPassword(u.rawPassword);
      if (!existing) {
        await rawDb.prepare(
          "INSERT INTO users (username, password_hash, display_name, role, employee_code, position, department, email_company, email_work, phone, status) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)"
        ).bind(
          cleanUsername,
          pHash,
          u.displayName,
          u.role,
          u.employeeCode,
          u.position,
          u.department,
          u.emailCompany,
          u.emailWork,
          u.phone,
          u.status
        ).run();
        usersSeeded++;
      } else {
        // Cập nhật thông tin bổ sung nếu user đã tồn tại
        await rawDb.prepare(
          "UPDATE users SET employee_code = ?, position = ?, department = ?, email_company = ?, email_work = ?, role = ? WHERE LOWER(username) = ?"
        ).bind(
          u.employeeCode,
          u.position,
          u.department,
          u.emailCompany,
          u.emailWork,
          u.role,
          cleanUsername
        ).run();
      }
    } catch (e) {
      console.error(`Lỗi khi nạp user ${cleanUsername}:`, e);
    }
  }

  return { positionsSeeded, usersSeeded, totalUsers: INITIAL_USERS.length, totalPositions: DEFAULT_POSITIONS.length };
}
